#!/usr/bin/env python3
"""
Regenerate main_standalone.py — the single-file QC build.

Splices the body of spread_ml.py into main.py at the [STANDALONE-EMBED]
marker, drops the cross-file import lines (tagged [STANDALONE-STRIP]), and
verifies the result compiles. Run after editing either source file:

    python quantconnect/build_standalone.py
"""

from __future__ import annotations

import os
import py_compile

HERE = os.path.dirname(os.path.abspath(__file__))


def build():
    spread = open(os.path.join(HERE, "spread_ml.py")).read()
    main = open(os.path.join(HERE, "main.py")).read()

    # spread_ml body = everything after its module docstring and import block.
    # Its imports (numpy / deque / dataclass) are re-declared in the embed
    # header below so the body is self-sufficient wherever it lands.
    marker = "import numpy as np\n"
    assert marker in spread, "spread_ml.py import block changed — update builder"
    body = spread.split(marker, 1)[1].strip("\n")

    # Drop the cross-file import from main.py.
    kept = [ln for ln in main.splitlines() if "[STANDALONE-STRIP]" not in ln]
    main = "\n".join(kept) + "\n"

    embed_marker = "# [STANDALONE-EMBED spread_ml]"
    assert embed_marker in main, "main.py embed marker missing — update builder"
    embedded = (
        "# =========================================================================== #\n"
        "# Embedded spread_ml — single-file build, generated by build_standalone.py.\n"
        "# Edit spread_ml.py / main.py and rebuild; do not edit this file directly.\n"
        "# =========================================================================== #\n"
        "from dataclasses import dataclass, field\n"
        "\n"
        + body + "\n\n\n"
        "# =========================================================================== #\n"
        "# The algorithm\n"
        "# =========================================================================== #"
    )
    main = main.replace(embed_marker, embedded, 1)
    main = main.replace(
        "Single-file build: run build_standalone.py to regenerate main_standalone.py\n"
        "with spread_ml embedded (one paste = whole project, no second file to forget).",
        "THIS IS THE SINGLE-FILE BUILD: spread_ml is embedded below, so this file\n"
        "alone is the whole QC project. Generated by build_standalone.py.")

    out = os.path.join(HERE, "main_standalone.py")
    open(out, "w").write(main)
    py_compile.compile(out, doraise=True)
    n = len(main.splitlines())
    print(f"wrote main_standalone.py: {n} lines, compiles OK")
    return n


if __name__ == "__main__":
    build()
